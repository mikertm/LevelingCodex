"""Write QuestFlightData.lua: every flight point and the world position of every zone, for travel plans.

    python tools/questflights.py          (writes QuestFlightData.lua)
    python tools/questflights.py --check  (fails if it is out of date)

Reads the committed game reference (tools/reference/forever.json, built by tools/gamedata.py from the
client's TaxiNodes, TaxiPath and UiMapAssignment tables): each flight point's name as the flight map
shows it, which faction can use it, the zone or city map it stands on, its position there and its
direct links; and each zone's place in the world, so the arrow can measure distances across zone
borders. The arrow uses them to plan trips through flight masters.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "tools" / "reference" / "forever.json"
OUT = ROOT / "QuestFlightData.lua"
HEADER = """-- Generated by tools/questflights.py from the Forever client reference (TaxiNodes, TaxiPath and
-- UiMapAssignment). Do not edit by hand: rerun the tool after a game data update.
local _, ns = ...
-- [node] = { name (as the flight map shows it), faction ("A", "H" or "AH"), map, x, y, { linked nodes } }
ns.questFlightNodes = {
"""
WORLD = """}
-- [map] = { continent, north, west, height, width [, true for a continent map] } in world yards: a
-- spot at x%, y% on the map is north - y% * height, west - x% * width.
ns.questWorld = {
"""


def num(value):
    text = ("%.3f" % value).rstrip("0").rstrip(".")
    return text if text not in ("-0", "") else "0"


def build():
    quests = json.loads(REF.read_text(encoding="utf-8"))["quests"]
    lines = [HEADER]
    for node, d in sorted(quests["taxi"].items(), key=lambda kv: int(kv[0])):
        name = d["name"]
        if any(ord(c) > 127 for c in name) or '"' in name:
            raise SystemExit("flight point %s has a name the game font can't draw: %r" % (node, name))
        links = ", ".join(str(n) for n in d["links"])
        lines.append('  [%s] = { "%s", "%s", %d, %s, %s, { %s } },\n'
                     % (node, name, d["faction"], d["map"], num(d["x"]), num(d["y"]), links))
    lines.append(WORLD)
    for map_id, d in sorted(quests["maps"].items(), key=lambda kv: int(kv[0])):
        if "world" in d:
            continent, north, west = d["world"][:3]
            whole = ", true" if d["world"][3:] == ["continent"] else ""
            lines.append("  [%s] = { %d, %s, %s, %s, %s%s }, -- %s\n"
                         % (map_id, continent, num(north), num(west), num(d["height"]), num(d["width"]), whole,
                            d["name"].encode("ascii", "replace").decode()))
    lines.append("}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if QuestFlightData.lua is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("QuestFlightData.lua is out of date: run tools/questflights.py")
            return 1
        print("QuestFlightData.lua is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("Wrote %s: %d flight points, %d maps." % (OUT.name, text.count('] = { "'), text.count(" }, -- ")))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
