"""Write QuestShopData.lua: the vendor-only items each route quest asks for, for the shopping card.

    tools/.cache/quest-venv/Scripts/python.exe -I tools/questshop.py          (writes QuestShopData.lua)
    tools/.cache/quest-venv/Scripts/python.exe -I tools/questshop.py --check  (fails if it is out of date)

For every quest any route step names (both factions), its QuestieDB item objectives whose item is
sold by a vendor and dropped by nothing (no creature, object or item drops). The count comes from
the quest's objective text ("Bring 3 Soothing Spices", "5 bottles of Junglevine Wine"); a text
that names no number gives 1, and the add-on uses the quest log's own count once you have the quest.
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamedata import load_lua_global  # noqa: E402
from questfacts import entity, lua_reader, record  # noqa: E402
from questroute import ROUTES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "QuestShopData.lua"
MAX_ITEMS = 6
HEADER = """-- Generated by tools/questshop.py from the QuestieDB Forever records: the items each route quest
-- asks for that only vendors sell, with the count its objective text names, for the vendor's
-- shopping card. Do not edit by hand: rerun the tool after route changes.
local _, ns = ...
ns.questShop = {
"""


def values(table):
    if isinstance(table, dict):
        return list(table.values())
    return list(table or [])


def route_quests(data):
    """Every quest ID a route step names, of any step type."""
    quests = set()
    for route in data.values():
        for section in route["sections"]:
            for step in section["steps"]:
                if step.get("quest"):
                    quests.add(int(step["quest"]))
    return quests


def count_for(name, texts):
    """The number before the item's name in the objective text ("3 Soothing Spices", "5 bottles of X"), else 1."""
    pattern = re.compile(r"(\d+)\s+(?:[A-Za-z]+\s+of\s+)?" + re.escape(name), re.I)
    for text in texts:
        found = pattern.search(text)
        if found:
            return int(found.group(1))
    return 1


def shop_for(quest, items):
    """[(itemID, count)] for the quest's item objectives that only vendors provide."""
    texts = [t for t in values(quest.get("objectivesText")) if isinstance(t, str)]
    found = []
    for objective in values((quest.get("objectives") or {}).get(3)):
        item_id = objective.get(1) if isinstance(objective, dict) else None
        item = record(items, item_id) if isinstance(item_id, int) else None
        if not item or not item.get("vendors"):
            continue
        if item.get("npcDrops") or item.get("objectDrops") or item.get("itemDrops"):
            continue
        name = item.get("name")
        count = count_for(name, texts) if isinstance(name, str) else 1
        if 1 <= count <= 100 and all(i != item_id for i, _ in found):
            found.append((item_id, count))
    return found[:MAX_ITEMS]


def render(table):
    lines = [HEADER]
    for quest_id in sorted(table):
        pairs = ", ".join(f"{{ {item}, {count} }}" for item, count in table[quest_id])
        lines.append(f"  [{quest_id}] = {{ {pairs} }},\n")
    lines.append("}\n")
    return "".join(lines)


def build():
    data = load_lua_global(ROUTES, "LevelingCodexQuests")
    lu, read = lua_reader()
    quests, items = (entity(lu, read, "forever", kind) for kind in ("quest", "item"))
    table = {}
    for quest_id in route_quests(data):
        quest = record(quests, quest_id)
        pairs = shop_for(quest, items) if quest else []
        if pairs:
            table[quest_id] = pairs
    return render(table)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if QuestShopData.lua is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("QuestShopData.lua is out of date: run tools/questshop.py")
            return 1
        print("QuestShopData.lua is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {text.count(' = {') - 1} quests.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
