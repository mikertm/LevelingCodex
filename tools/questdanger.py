"""Write QuestDangerData.lua: hostile elites and rares on the route's maps, for step warnings.

    tools/.cache/quest-venv/Scripts/python.exe -I tools/questdanger.py          (writes QuestDangerData.lua)
    tools/.cache/quest-venv/Scripts/python.exe -I tools/questdanger.py --check  (fails if it is out of date)

Every NPC the cached QuestieDB Forever records rank as elite, rare elite, boss or rare, level 60 or
lower, that isn't friendly to both factions and spawns on a map the tools know (questfacts ZONES),
with up to four spawn clusters per map (busiest first). The step window warns when one is near the
current step and not outleveled.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from questfacts import ZONES, entity, lua_reader, record  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "QuestDangerData.lua"
KINDS = {1: "elite", 2: "rareelite", 3: "boss", 4: "rare"}
MAX_SPOTS = 4
HEADER = """-- Generated by tools/questdanger.py from the QuestieDB Forever records: hostile elites and rares per
-- map, { name, minLevel, maxLevel, kind, friendly (faction letters or ""), spots = { x, y, ... } },
-- for the step window's warnings. Do not edit by hand: rerun the tool.
local _, ns = ...
ns.questDanger = {
"""


def clusters(coords):
    """Spawn points grouped into 5% squares; the busiest squares' centres first."""
    cells = {}
    for xy in coords.values():
        x, y = xy.get(1), xy.get(2)
        if isinstance(x, (int, float)) and isinstance(y, (int, float)) and 0 <= x <= 100 and 0 <= y <= 100:
            cells.setdefault((int(x // 5), int(y // 5)), []).append((x, y))
    busiest = sorted(cells.values(), key=lambda c: (-len(c), c[0]))[:MAX_SPOTS]
    return [(round(sum(p[0] for p in c) / len(c), 1), round(sum(p[1] for p in c) / len(c), 1)) for c in busiest]


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build():
    lu, read = lua_reader()
    npcs = entity(lu, read, "forever", "npc")
    keys, rows, traces = npcs
    ids = set(rows.keys())
    if traces is not None:
        ids.update(traces.keys())
    area_map = {}
    for area, map_id in ZONES.values():
        area_map.setdefault(area, map_id)
    by_map = {}
    for npc_id in sorted(int(i) for i in ids):
        entry = record(npcs, npc_id)
        kind = KINDS.get(entry.get("rank"))
        name = entry.get("name")
        friendly = entry.get("friendlyToFaction") or ""
        low, high = entry.get("minLevel"), entry.get("maxLevel")
        if not kind or not isinstance(name, str) or not name.isascii() or "A" in friendly and "H" in friendly:
            continue
        if not isinstance(high, int) or high > 60 or high < 1:
            continue
        low = low if isinstance(low, int) and 0 < low <= high else high
        for area, coords in (entry.get("spawns") or {}).items():
            map_id = area_map.get(area)
            if map_id is None or not isinstance(coords, dict):
                continue
            spots = clusters(coords)
            if spots:
                by_map.setdefault(map_id, []).append((name, low, high, kind, friendly, spots))
    lines = [HEADER]
    for map_id in sorted(by_map):
        lines.append(f"  [{map_id}] = {{\n")
        for name, low, high, kind, friendly, spots in sorted(by_map[map_id], key=lambda d: (d[2], d[0])):
            flat = ", ".join(f"{x:g}, {y:g}" for x, y in spots)
            lines.append(f"    {{ {lua_string(name)}, {low}, {high}, \"{kind}\", \"{friendly}\", spots = {{ {flat} }} }},\n")
        lines.append("  },\n")
    lines.append("}\n")
    return "".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if QuestDangerData.lua is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("QuestDangerData.lua is out of date: run tools/questdanger.py")
            return 1
        print("QuestDangerData.lua is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    count = text.count('spots = {')
    print(f"Wrote {OUT.name}: {count} creatures on {text.count('] = {')} maps, {len(text) // 1024} KB.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
