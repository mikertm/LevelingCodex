"""Write QuestMobData.lua: the creatures each route quest's objectives need, for the target button.

    tools/.cache/quest-venv/Scripts/python.exe -I tools/questmobs.py          (writes QuestMobData.lua)
    tools/.cache/quest-venv/Scripts/python.exe -I tools/questmobs.py --check  (fails if it is out of date)

Kill objectives (and kill-credit groups) come first, then the creatures that drop item objectives,
kept to the ones that spawn on the maps of the quest's complete steps (busiest first). Facts come
from the cached QuestieDB Forever records (see tools/questfacts.py); a quest they don't have gets no
entry, and a step can still list its own `mobs`.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamedata import load_lua_global  # noqa: E402
from questfacts import ZONES, entity, lua_reader, record  # noqa: E402
from questroute import ROUTES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "QuestMobData.lua"
MAX_NAMES = 6
HEADER = """-- Generated by tools/questmobs.py from the QuestieDB Forever records: the creatures each route
-- quest's objectives need (kills first, then drops near the quest's steps), for the step window's
-- target button. Do not edit by hand: rerun the tool after route changes.
local _, ns = ...
ns.questMobs = {
"""


def route_quests(data):
    """Quest ID -> the maps of its complete steps, for every quest a route completes."""
    quests = {}
    for route in data.values():
        for section in route["sections"]:
            for step in section["steps"]:
                if step.get("type") == "complete" and step.get("quest"):
                    quests.setdefault(int(step["quest"]), set()).add(step.get("map"))
    return quests


def ascii_name(entry):
    name = entry.get("name") if entry else None
    return name if isinstance(name, str) and name.isascii() and name.strip() else None


def spawn_count(entry, areas):
    return sum(len(coords) for area, coords in (entry.get("spawns") or {}).items()
               if area in areas and isinstance(coords, dict))


def quest_areas(quest, maps):
    """QuestieDB zone IDs for the quest: its steps' maps (known zones) and the quest's own zone."""
    areas = {area for area, map_id in ZONES.values() if map_id in maps}
    zone = quest.get("zoneOrSort")
    if isinstance(zone, int) and zone > 0:
        areas.add(zone)
    return areas


def mobs_for(quest, maps, npcs, items):
    objectives = quest.get("objectives") or {}
    areas = quest_areas(quest, maps)
    names = []

    def add(name):
        if name and name not in names:
            names.append(name)

    for objective in (objectives.get(1) or {}).values():
        add(ascii_name(record(npcs, objective.get(1))))
    for credit in (objectives.get(5) or {}).values():
        add(ascii_name(record(npcs, credit.get(2))) if credit.get(2) else None)
        for npc in (credit.get(1) or {}).values():
            add(ascii_name(record(npcs, npc)))
    for objective in (objectives.get(3) or {}).values():
        item = record(items, objective.get(1))
        droppers = []
        for npc in (item.get("npcDrops") or {}).values():
            entry = record(npcs, npc)
            name = ascii_name(entry)
            if name:
                droppers.append((spawn_count(entry, areas), name))
        near = [d for d in droppers if d[0] > 0]
        if near:
            droppers = near
        elif len(droppers) > 4:
            droppers = []  # none spawn in the quest's zones and too many to guess
        for _, name in sorted(droppers, key=lambda d: -d[0]):
            add(name)
    return names[:MAX_NAMES]


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(table):
    lines = [HEADER]
    for quest_id in sorted(table):
        names = ", ".join(lua_string(n) for n in table[quest_id])
        lines.append(f"  [{quest_id}] = {{ {names} }},\n")
    lines.append("}\n")
    return "".join(lines)


def build():
    data = load_lua_global(ROUTES, "LevelingCodexQuests")
    lu, read = lua_reader()
    quests, npcs, items = (entity(lu, read, "forever", kind) for kind in ("quest", "npc", "item"))
    table = {}
    for quest_id, maps in route_quests(data).items():
        quest = record(quests, quest_id)
        names = mobs_for(quest, maps, npcs, items) if quest else []
        if names:
            table[quest_id] = names
    return render(table)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if QuestMobData.lua is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("QuestMobData.lua is out of date: run tools/questmobs.py")
            return 1
        print("QuestMobData.lua is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {text.count(' = {') } quests.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
