"""Write QuestNPCData.lua: each route quest's giver, finisher and first target, for the portrait.

    tools/.cache/quest-venv/Scripts/python.exe -I tools/questnpcs.py          (writes QuestNPCData.lua)
    tools/.cache/quest-venv/Scripts/python.exe -I tools/questnpcs.py --check  (fails if it is out of date)

`start` = the first creature QuestieDB says starts the quest, `finish` = the first that ends it, `mob`
= the first creature a kill objective names, else the first kill-credit creature. A quest started by
an object or an item gets no `start`; the step window then shows the step's icon in the portrait
ring. Facts come from the cached QuestieDB Forever records (see tools/questfacts.py).
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamedata import load_lua_global  # noqa: E402
from questfacts import entity, lua_reader, record  # noqa: E402
from questroute import ROUTES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "QuestNPCData.lua"
HEADER = """-- Generated by tools/questnpcs.py from the QuestieDB Forever records: each route quest's giver
-- (start), finisher (finish) and first kill target (mob), creature IDs for the step window's
-- portrait. Do not edit by hand: rerun the tool after route changes.
local _, ns = ...
ns.questNPCs = {
"""
STEP_TYPES = ("accept", "turnin", "complete")


def route_quests(data):
    """Every quest a route accepts, turns in or completes."""
    quests = set()
    for route in data.values():
        for section in route["sections"]:
            for step in section["steps"]:
                if step.get("type") in STEP_TYPES and step.get("quest"):
                    quests.add(int(step["quest"]))
    return quests


def first(values):
    """The first positive integer in a QuestieDB list (a dict keyed 1, 2, ...), else None."""
    if not isinstance(values, dict):
        return None
    for key in sorted(k for k in values if isinstance(k, int)):
        value = values[key]
        if isinstance(value, int) and value > 0:
            return value
    return None


def npcs_for(quest):
    entry = {}
    start = first((quest.get("startedBy") or {}).get(1))
    finish = first((quest.get("finishedBy") or {}).get(1))
    if start:
        entry["start"] = start
    if finish:
        entry["finish"] = finish
    objectives = quest.get("objectives") or {}
    mob = None
    for key in sorted(k for k in (objectives.get(1) or {}) if isinstance(k, int)):
        candidate = (objectives[1][key] or {}).get(1)
        if isinstance(candidate, int) and candidate > 0:
            mob = candidate
            break
    if not mob:
        for key in sorted(k for k in (objectives.get(5) or {}) if isinstance(k, int)):
            credit = objectives[5][key] or {}
            mob = first(credit.get(1)) or (credit.get(2) if isinstance(credit.get(2), int) else None)
            if mob:
                break
    if mob:
        entry["mob"] = mob
    return entry


def render(table):
    lines = [HEADER]
    for quest_id in sorted(table):
        fields = ", ".join(f"{key} = {table[quest_id][key]}" for key in ("start", "finish", "mob")
                           if key in table[quest_id])
        lines.append(f"  [{quest_id}] = {{ {fields} }},\n")
    lines.append("}\n")
    return "".join(lines)


def build():
    data = load_lua_global(ROUTES, "LevelingCodexQuests")
    lu, read = lua_reader()
    quests = entity(lu, read, "forever", "quest")
    table = {}
    for quest_id in route_quests(data):
        quest = record(quests, quest_id)
        entry = npcs_for(quest) if quest else {}
        if entry:
            table[quest_id] = entry
    return render(table)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if QuestNPCData.lua is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("QuestNPCData.lua is out of date: run tools/questnpcs.py")
            return 1
        print("QuestNPCData.lua is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {text.count(' = {')} quests.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
