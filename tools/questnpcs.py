"""Write QuestNPCData.lua: each route quest's giver, finisher and first target, for the portrait.

    tools/.cache/quest-venv/Scripts/python.exe -I tools/questnpcs.py          (writes QuestNPCData.lua)
    tools/.cache/quest-venv/Scripts/python.exe -I tools/questnpcs.py --check  (fails if it is out of date)

`start` = the first creature QuestieDB says starts the quest, `finish` = the first that ends it, `mob`
= the first creature a kill objective names, else the first kill-credit creature. A quest started by
an object or an item gets no `start`; the step window then shows the step's icon in the portrait
ring. Facts come from the cached QuestieDB Forever records (see tools/questfacts.py).

`by` = { ["NPC name"] = creature } for the route's accept/turn-in steps that name another NPC than
`start`/`finish` (a class quest every trainer gives, a breadcrumb with several givers, a giver
QuestieDB doesn't list): the quest's own givers/finishers by that name first, else the one NPC with
spawns QuestieDB knows by that name. The portrait shows the step's NPC.
"""
import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamedata import load_lua_global  # noqa: E402
from questfacts import entity, lua_reader, record  # noqa: E402
from questroute import ROUTES  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "QuestNPCData.lua"
HEADER = """-- Generated by tools/questnpcs.py from the QuestieDB Forever records: each route quest's giver
-- (start), finisher (finish) and first kill target (mob), creature IDs for the step window's
-- portrait. Do not edit by hand: rerun the tool after route changes.
local _, ns = ...
ns.questNPCs = {
"""
STEP_TYPES = ("accept", "turnin", "complete")
FIELD = {"accept": "start", "turnin": "finish"}


def route_quests(data):
    """Every quest a route accepts, turns in or completes."""
    quests = set()
    for route in data.values():
        for section in route["sections"]:
            for step in section["steps"]:
                if step.get("type") in STEP_TYPES and step.get("quest"):
                    quests.add(int(step["quest"]))
    return quests


def first(values):
    """The first positive integer in a QuestieDB list (a dict keyed 1, 2, ...), else None."""
    if not isinstance(values, dict):
        return None
    for key in sorted(k for k in values if isinstance(k, int)):
        value = values[key]
        if isinstance(value, int) and value > 0:
            return value
    return None


def npcs_for(quest):
    entry = {}
    start = first((quest.get("startedBy") or {}).get(1))
    finish = first((quest.get("finishedBy") or {}).get(1))
    if start:
        entry["start"] = start
    if finish:
        entry["finish"] = finish
    objectives = quest.get("objectives") or {}
    mob = None
    for key in sorted(k for k in (objectives.get(1) or {}) if isinstance(k, int)):
        candidate = (objectives[1][key] or {}).get(1)
        if isinstance(candidate, int) and candidate > 0:
            mob = candidate
            break
    if not mob:
        for key in sorted(k for k in (objectives.get(5) or {}) if isinstance(k, int)):
            credit = objectives[5][key] or {}
            mob = first(credit.get(1)) or (credit.get(2) if isinstance(credit.get(2), int) else None)
            if mob:
                break
    if mob:
        entry["mob"] = mob
    return entry


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ids(values):
    """Every positive integer in a QuestieDB list, in order."""
    if not isinstance(values, dict):
        return []
    return [values[k] for k in sorted(k for k in values if isinstance(k, int))
            if isinstance(values[k], int) and values[k] > 0]


def step_npcs(data):
    """(quest, field, NPC name) for every accept and turn-in step that names an NPC."""
    found = set()
    for route in data.values():
        for section in route["sections"]:
            for step in section["steps"]:
                field = FIELD.get(step.get("type"))
                if field and step.get("quest") and isinstance(step.get("npc"), str):
                    found.add((int(step["quest"]), field, step["npc"]))
    return found


def render(table):
    lines = [HEADER]
    for quest_id in sorted(table):
        entry = table[quest_id]
        fields = [f"{key} = {entry[key]}" for key in ("start", "finish", "mob") if key in entry]
        if entry.get("by"):
            pairs = ", ".join(f"[{lua_string(name)}] = {entry['by'][name]}" for name in sorted(entry["by"]))
            fields.append(f"by = {{ {pairs} }}")
        lines.append(f"  [{quest_id}] = {{ {', '.join(fields)} }},\n")
    lines.append("}\n")
    return "".join(lines)


def build():
    data = load_lua_global(ROUTES, "LevelingCodexQuests")
    lu, read = lua_reader()
    quests = entity(lu, read, "forever", "quest")
    npcs = entity(lu, read, "forever", "npc")
    names, by_name = {}, {}
    for npc_id in npcs[1].keys():
        npc = record(npcs, npc_id)
        if npc and isinstance(npc.get("name"), str):
            names[npc_id] = npc["name"]
            if npc.get("spawns"):
                by_name.setdefault(npc["name"], []).append(npc_id)
    table = {}
    for quest_id in route_quests(data):
        quest = record(quests, quest_id)
        entry = npcs_for(quest) if quest else {}
        if entry:
            table[quest_id] = entry
    for quest_id, field, name in sorted(step_npcs(data)):
        entry = table.get(quest_id, {})
        if entry.get(field) and names.get(entry[field]) == name:
            continue
        quest = record(quests, quest_id) or {}
        own = ids((quest.get("startedBy" if field == "start" else "finishedBy") or {}).get(1))
        spawned = by_name.get(name, [])
        match = [i for i in own if names.get(i) == name] or (spawned if len(spawned) == 1 else [])
        if match:
            table.setdefault(quest_id, entry).setdefault("by", {})[name] = match[0]
    return render(table)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if QuestNPCData.lua is out of date")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != text:
            print("QuestNPCData.lua is out of date: run tools/questnpcs.py")
            return 1
        print("QuestNPCData.lua is up to date.")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT.name}: {text.count(chr(10) + '  [')} quests.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
